  const KEY = 'gpu-observatory-language';
  let language = 'zh';
  try { if (localStorage.getItem(KEY) === 'en') language = 'en'; } catch {}
  function t(key, values = {}) {
    const translated = language === 'en' ? (messages[key] ?? key) : key;
    return translated.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
  }
  function bind(element, key, values = {}) {
    element.setAttribute('data-i18n', key);
    element.setAttribute('data-i18n-values', JSON.stringify(values));
    element.textContent = t(key, values);
  }
  function apply() {
    document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
    for (const node of document.querySelectorAll('[data-i18n]')) {
      let values = {};
      try { values = JSON.parse(node.getAttribute('data-i18n-values') || '{}'); } catch {}
      node.textContent = t(node.getAttribute('data-i18n'), values);
    }
    for (const attr of ['aria-label', 'placeholder', 'title']) {
      for (const node of document.querySelectorAll('[data-i18n-' + attr + ']')) node.setAttribute(attr, t(node.getAttribute('data-i18n-' + attr)));
    }
    for (const control of document.querySelectorAll('[data-language-switch]')) control.value = language;
    for (const link of document.querySelectorAll('link[rel="manifest"]')) link.setAttribute('href', language === 'en' ? '/manifest.en.webmanifest' : '/manifest.webmanifest');
  }
  function setLanguage(next, persist = true) {
    if (!['zh', 'en'].includes(next)) return false;
    language = next;
    if (persist) try { localStorage.setItem(KEY, language); } catch {}
    apply(); document.dispatchEvent(new CustomEvent('ui-language', { detail: language }));
    return true;
  }
  window.I18n = { t, bind, apply, setLanguage, language: () => language, locale: () => language === 'en' ? 'en-US' : 'zh-CN', messages: Object.freeze(messages) };
  for (const control of document.querySelectorAll('[data-language-switch]')) control.addEventListener('change', event => setLanguage(event.target.value));
  window.addEventListener('storage', event => { if (event.key === KEY) setLanguage(event.newValue === 'en' ? 'en' : 'zh', false); });
  apply();
